"""Regression tests for real Plant Simulation 2404 image export signatures.

The fake PNGs below are ONLY test fixtures; no test pretends that they were
captured from Siemens. The real export must run on the user's Windows machine.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest
import struct
import zlib

from sze_virtualis_eszkoztervezes.evidence import capture
from sze_virtualis_eszkoztervezes.resume import verify_saved_run


class DummySiemensExporter:
    root = ".Models.Model"

    def __init__(self, output: Path):
        self.output_dir = output
        self.commands = []

    def execute(self, command: str, description: str = ""):
        self.commands.append(command)
        method = ".copyBitmapToFile("
        assert method in command
        obj, args = command.split(method, 1)
        assert args.endswith(")")
        path_argument, *numbers = args[:-1].split(",")
        assert len(numbers) == (2 if obj.endswith("Allomas_Statisztika") else 4)
        if obj.endswith("Allomas_Statisztika"):
            assert numbers == ["1500", "900"]
        else:
            assert numbers[:2] == ["0", "0"]
        path = Path(json.loads(path_argument))
        path.parent.mkdir(parents=True, exist_ok=True)
        # Genuine *valid* PNG fixture generated by Pillow, not fake Siemens evidence.
        pixels = bytearray()
        for y in range(100):
            pixels.append(0)  # PNG scanline filter: none
            for x in range(150):
                pixels.extend(((x * 17 + y * 13) % 256,
                               (x * 7 + y * 19) % 256,
                               (x * 29 + y * 11) % 256))

        def png_chunk(kind, data):
            return (struct.pack(">I", len(data)) + kind + data
                    + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF))
        png = b"\x89PNG\r\n\x1a\n"
        png = (png
               + png_chunk(b"IHDR", struct.pack(">IIBBBBB", 150, 100, 8, 2,
                                                 0, 0, 0))
               + png_chunk(b"IDAT", zlib.compress(bytes(pixels)))
               + png_chunk(b"IEND", b""))
        path.write_bytes(png)


def prepare_complete_report(folder: Path):
    report = dict(
        complete=True,
        processed=10000,
        pass_quantity_and_quality_tolerance=True,
        good=7010,
        bad=2990,
        source_output_count=10000,
        packed=7010,
        loaded_at_station_1=4627,
        loaded_at_station_2=2383,
        lot_lead_time_seconds=4212000,
    )
    (folder / "simulation_result.json").write_text(
        json.dumps(report), encoding="utf-8"
    )
    (folder / "config_validation.json").write_text(
        json.dumps({"siemens_live_verification": True, "errors": []}),
        encoding="utf-8"
    )
    spp = folder / "ABC123.spp"
    # Test-only placeholder: capture checks real app screenshot signatures;
    # a true .spp is produced only by Plant Simulation on Windows.
    spp.write_bytes(b"Test fixture, NOT a Siemens SPP" * 100)
    return spp, report


def test_capture_has_exact_frame_and_chart_arity(tmp_path: Path):
    spp, _report = prepare_complete_report(tmp_path)
    mock = DummySiemensExporter(tmp_path)
    manifest = capture(mock, spp)
    assert len(manifest["screenshots"]) == 5
    assert len(mock.commands) == 5
    assert all(".copyBitmapToFile(" in cmd for cmd in mock.commands)
    assert manifest["synthetic_images"] is False
    # The flag in the fixture describes the production capture path;
    # this is mocked test data, never published as real evidence.
    assert (tmp_path / "screenshots" / "05_allomasstatisztika.png").is_file()


def test_saved_model_resume_verifies_every_counter_and_time(tmp_path: Path):
    spp, report = prepare_complete_report(tmp_path)
    root = ".Models.Model"

    class FakeLoadedModel:
        output_dir = tmp_path
        root = ".Models.Model"

        def get(self, expression):
            pairs = {
                root + ".Kiszallitott_JO.StatDeleted": report["good"],
                root + ".Minosegellenorzes.Rossz_Termekek.StatDeleted":
                    report["bad"],
                root + ".PC_Beerkezes_10000.StatNumOut":
                    report["source_output_count"],
                root + ".Csomagolas.Csomagolas_10perc.StatNumOut":
                    report["packed"],
                root + ".Szallitas_Elokeszites.Rakodo1_5perc.StatNumOut":
                    report["loaded_at_station_1"],
                root + ".Szallitas_Elokeszites.Rakodo2_10perc.StatNumOut":
                    report["loaded_at_station_2"],
                root + ".EventController.SimTime":
                    report["lot_lead_time_seconds"],
            }
            return pairs[expression]

    verify_saved_run(FakeLoadedModel(), spp)


def test_resume_rejects_mismatched_spp(tmp_path: Path):
    spp, report = prepare_complete_report(tmp_path)

    class WrongLoadedModel:
        root = ".Models.Model"
        output_dir = tmp_path

        def get(self, expression):
            if expression.endswith("Kiszallitott_JO.StatDeleted"):
                return report["good"] - 1
            return 0

    with pytest.raises(RuntimeError, match="elter"):
        verify_saved_run(WrongLoadedModel(), spp)


def test_capture_rejects_unverified_run(tmp_path: Path):
    spp, report = prepare_complete_report(tmp_path)
    report["pass_quantity_and_quality_tolerance"] = False
    (tmp_path / "simulation_result.json").write_text(
        json.dumps(report), encoding="utf-8"
    )
    mock = DummySiemensExporter(tmp_path)
    with pytest.raises(RuntimeError, match="Nem igazolt"):
        capture(mock, spp)
    assert not mock.commands
